def _nan(x):
    try:
        v = float(x)
    except (TypeError, ValueError):
        return np.nan
    return v if np.isfinite(v) else np.nan


def short_snapshot(B, js) -> dict:
    """{j: {"ratio": 券資比, "inc10": 近 10 日融券增減 ÷ 20 日均量, "sbal": 融券張數}}；資料不足時為 NaN。"""
    out = {}
    SB, MB, V = (B.a.get(k) for k in ("Q_SB", "Q_MB", "Q_V"))
    if SB is None or MB is None:
        return out
    for j in js:
        sb = SB[:, j].astype(float)
        mb = MB[:, j].astype(float)
        ok = np.isfinite(sb) & np.isfinite(mb)
        if ok.sum() < 12:
            out[j] = {"ratio": np.nan, "inc10": np.nan, "sbal": np.nan}
            continue
        idx = np.where(ok)[0]
        s1, m1 = sb[idx[-1]], mb[idx[-1]]
        s0 = sb[idx[-11]]
        v20 = V[idx[-20:], j].astype(float) if V is not None else np.array([])
        vol = float(np.nanmean(v20)) if np.isfinite(v20).any() else np.nan
        out[j] = {"ratio": s1 / m1 if m1 > 0 else np.nan,
                  "inc10": (s1 - s0) / vol if ui_ok(vol) and vol > 0 else np.nan, "sbal": s1}
    return out


def ui_ok(x) -> bool:
    return x is not None and np.isfinite(_nan(x))


def short_crowded(B, n: int = 15, top: int = 500, min_sbal: float = 500) -> pd.DataFrame:
    """成交金額（近 20 日）前 top 名、融券 ≥ min_sbal 張之中，券資比最高的 n 檔。"""
    SB, MB, V, C = (B.a.get(k) for k in ("Q_SB", "Q_MB", "Q_V", "Q_C"))
    if SB is None or MB is None or V is None or C is None or len(C) < 61:
        return pd.DataFrame()
    import warnings
    Cf = pd.DataFrame(C.astype(float)).ffill().to_numpy()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        amt = np.nanmean(V[-20:].astype(float) * Cf[-20:], axis=0)
    amt = np.where(np.isfinite(amt), amt, -1)
    uni = np.argsort(-amt)[:top]
    rows = []
    snap = short_snapshot(B, uni)
    for j in uni:
        s = snap.get(j) or {}
        if not ui_ok(s.get("ratio")) or s.get("sbal", 0) < min_sbal:
            continue
        c = Cf[:, j]
        rows.append({"j": int(j), "ratio": s["ratio"], "inc10": s["inc10"], "sbal": s["sbal"],
                     "r20": c[-1] / c[-21] - 1 if c[-21] > 0 else np.nan, "d60": c[-1] / np.nanmax(c[-60:]) - 1})
    df = pd.DataFrame(rows)
    return df.sort_values("ratio", ascending=False).head(n).reset_index(drop=True) if len(df) else df


def family_shares(weights: dict, factors, families) -> dict:
    """權重（{因子: 權重}）→ 各家族絕對值占比，另加動能群組 mom 與最大單一因子。"""
    fam = dict(zip(factors, families))
    w = {f: abs(float(x)) for f, x in (weights or {}).items() if np.isfinite(_nan(x))}
    tot = sum(w.values())
    if tot <= 0:
        return {}
    out = {k: sum(x for f, x in w.items() if fam.get(f) == k) / tot for k in FAMILY_ZH}
    out["mom"] = sum(x for f, x in w.items() if f in MOMENTUM) / tot
    top = max(w, key=w.get)
    out["top"], out["top_w"] = top, w[top] / tot
    return out
