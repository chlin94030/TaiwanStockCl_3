def _shock_group(up: bool, inst: float, marg: float, rev3: float, pre20: float) -> str:
    ok = lambda x: x is not None and np.isfinite(x)                        # noqa: E731
    if up:
        if ok(inst) and inst > 0.05 and ok(rev3) and rev3 > 0.20:
            return "法人買＋營收 > 20%"
        if ok(marg) and marg > 0.05 and ok(inst) and inst < -0.05:
            return "融資追＋法人賣"
        if ok(inst) and inst < -0.05:
            return "法人賣（< −5%）"
        if ok(inst) and inst > 0.05:
            return "法人買（外資＋投信 > 當日量 5%）"
        if ok(rev3) and rev3 <= 0:
            return "營收年增 ≤ 0"
        if ok(pre20) and pre20 > 0.30:
            return "前 20 日已漲 > 30%"
        return "全部"
    if ok(inst) and inst > 0.05:
        return "法人買（逢低承接）"
    if ok(inst) and inst < -0.05:
        return "法人賣"
    if ok(rev3) and rev3 <= 0:
        return "營收年增 ≤ 0"
    if ok(pre20) and pre20 > 0.30:
        return "前 20 日已漲 > 30%（漲多回檔）"
    return "全部"


def shock_events(B, days: int = 10, top: int = 800, thr: float = 0.07, volx: float = 3.0) -> pd.DataFrame:
    """近 days 個交易日的消息面急漲／急跌股（定義同 v2.5 研究），附歷史上同類事件之後的表現。資料＝每日研究資料包。"""
    import warnings
    need = ("Q_C", "Q_V")
    if any(k not in B.a for k in need) or "q_days" not in B.meta:
        return pd.DataFrame()
    days_ix = pd.DatetimeIndex(B.meta["q_days"])
    C = pd.DataFrame(B.a["Q_C"].astype(float), index=days_ix).ffill()
    V = pd.DataFrame(B.a["Q_V"].astype(float), index=days_ix)
    RF = pd.DataFrame(B.a["Q_RF"].astype(float), index=days_ix) if "Q_RF" in B.a else C.shift(1)
    ret = C / RF.where(RF > 0) - 1
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", RuntimeWarning)
        v20 = V.shift(1).rolling(20, min_periods=15).mean()
        amt20 = (V * C).rolling(20, min_periods=15).mean()
    fi = pd.DataFrame(B.a["Q_FI"].astype(float), index=days_ix).fillna(0) if "Q_FI" in B.a else None
    tr = pd.DataFrame(B.a["Q_TR"].astype(float), index=days_ix).fillna(0) if "Q_TR" in B.a else None
    inst = (fi + tr) / V.where(V > 0) if fi is not None and tr is not None else None
    mb = pd.DataFrame(B.a["Q_MB"].astype(float), index=days_ix) if "Q_MB" in B.a else None
    marg = mb.diff() / V.where(V > 0) if mb is not None else None
    pre20 = C / C.shift(20) - 1
    rev3 = None
    if "LATEST_RAW" in B.a and "f_rev_yoy3" in B.factors:
        rev3 = B.a["LATEST_RAW"][:, B.factors.index("f_rev_yoy3")].astype(float)
    rows = []
    n = len(days_ix)
    for i in range(max(21, n - days), n):
        uni = amt20.iloc[i].rank(ascending=False) <= top
        r = ret.iloc[i]
        vx = V.iloc[i] / v20.iloc[i]
        hit = uni & (vx >= volx) & ((r >= thr) | (r <= -thr))
        for j in np.where(hit.to_numpy())[0]:
            up = bool(r.iloc[j] > 0)
            prev_up = bool(((ret.iloc[max(0, i - 20):i, j] >= thr) & (V.iloc[max(0, i - 20):i, j] / v20.iloc[max(0, i - 20):i, j] >= volx)).any())
            iv = float(inst.iloc[i, j]) if inst is not None else np.nan
            mv = float(marg.iloc[i, j]) if marg is not None else np.nan
            rv = float(rev3[j]) if rev3 is not None else np.nan
            pv = float(pre20.iloc[i, j])
            g = _shock_group(up, iv, mv, rv, pv)
            if up and prev_up and g == "全部":
                g = "連續炒作（前 20 日已有急漲）"
            ref = {x[0]: x for x in (SHOCK_UP if up else SHOCK_DOWN)}.get(g) or (SHOCK_UP if up else SHOCK_DOWN)[0]
            rows.append({"date": days_ix[i], "j": int(j), "up": up, "ret": float(r.iloc[j]), "volx": float(vx.iloc[j]),
                         "inst": iv, "marg": mv, "rev3": rv, "pre20": pv, "repeat": prev_up, "group": g,
                         "since": float(C.iloc[-1, j] / C.iloc[i, j] - 1), "days_ago": int(n - 1 - i),
                         "hist_x20": ref[4], "hist_x60": ref[5], "hist_win20": ref[6]})
    df = pd.DataFrame(rows)
    return df.sort_values(["date", "ret"], ascending=[False, False]).reset_index(drop=True) if len(df) else df
