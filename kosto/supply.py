def peers(ticker: str) -> dict[str, list[str]]:
    """橫向：同一細族群的其他公司（同業競爭）。"""
    return {g: [t for t, _ in SUBGROUPS[g]["members"] if t != ticker] for g in groups_of(ticker)}


