def members(gid: str, universe=None) -> list[tuple[str, str]]:
    """細族群的代表個股（只回傳資料庫裡有的代號）。"""
    xs = SUBGROUPS[gid]["members"]
    return [(t, r) for t, r in xs if universe is None or t in universe]


def theme_members(th: dict, universe=None) -> list[tuple[str, str]]:
    out, seen = [], set()
    for t, r in th.get("members", []):
        if t not in seen and (universe is None or t in universe):
            out.append((t, r)); seen.add(t)
    for g in th.get("groups", []):
        for t, r in SUBGROUPS[g]["members"]:
            if t not in seen and (universe is None or t in universe):
                out.append((t, f"{SUBGROUPS[g]['name']}：{r}")); seen.add(t)
    return out


def groups_of(ticker: str) -> list[str]:
    return [g for g, d in SUBGROUPS.items() if any(t == ticker for t, _ in d["members"])]


def themes_of(ticker: str) -> list[str]:
    return [th["name"] for th in THEMES if any(t == ticker for t, _ in theme_members(th))]


